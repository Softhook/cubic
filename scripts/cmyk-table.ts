/**
 * Sets the press profile the Art Lab's CMYK PDFs are made for, and builds the table they convert with.
 *   npm run print:cmyk-table -- [--profile <press.icc>] [--srgb <sRGB.icc>] [--condition FOGRA39]
 *
 * The profile is copied to apps/web/src/print/press.icc, which every PDF embeds as its output intent,
 * and ImageMagick (LittleCMS) converts an 18 × 18 × 18 grid of sRGB colours with it, relative
 * colorimetric with black point compensation, so the art's darkest tones stay apart instead of all
 * printing as the press's black. The result is apps/web/src/print/cmykTable.ts; the export
 * interpolates between grid points. Without --profile it rebuilds the table from the current press.icc.
 * `--condition` is the profile's registered printing condition: FOGRA39 for ISO Coated v2 (ECI).
 */
import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, writeFileSync } from 'node:fs';
import { arg } from './mobile-common';

/** Grid points per channel: 18, so they fall on whole values (every 15), as the export interpolates. */
const GRID = 18;
const PRESS = 'apps/web/src/print/press.icc';
const profile = arg('--profile') ?? PRESS;
const srgb = arg('--srgb') ?? '/System/Library/ColorSync/Profiles/sRGB Profile.icc';
const condition = arg('--condition') ?? 'FOGRA39';
for (const p of [profile, srgb]) if (!existsSync(p)) throw new Error(`No profile at ${p}: pass --profile and --srgb`);

if (profile !== PRESS) copyFileSync(profile, PRESS);

const steps = Array.from({ length: GRID }, (_, i) => (i * 255) / (GRID - 1));
const rgb = Buffer.from(steps.flatMap((r) => steps.flatMap((g) => steps.flatMap((b) => [r, g, b]))));
const size = `${GRID ** 3}x1`;
const cmyk = execFileSync(
  'magick',
  [
    '-size',
    size,
    '-depth',
    '8',
    'rgb:-',
    '-profile',
    srgb,
    '-intent',
    'relative',
    '-black-point-compensation',
    '-profile',
    PRESS,
    '-depth',
    '8',
    'cmyk:-',
  ],
  { input: rgb, maxBuffer: 1 << 24 },
);
if (cmyk.length !== GRID ** 3 * 4) throw new Error(`ImageMagick returned ${cmyk.length} bytes`);
const name = execFileSync('magick', ['-size', '1x1', 'xc:white', '-profile', PRESS, '-format', '%[icc:description]', 'info:'])
  .toString()
  .trim();

const out = 'apps/web/src/print/cmykTable.ts';
const quote = (s: string) => `'${s.replace(/[\\']/g, '\\$&')}'`;
writeFileSync(
  out,
  `/** Generated by scripts/cmyk-table.ts (npm run print:cmyk-table): do not edit. */\n\n` +
    `/** sRGB → CMYK for ${name}, relative colorimetric with black point compensation: a grid of ${GRID}³ points, C M Y K bytes, red slowest. */\n` +
    `export const CMYK_TABLE = {\n` +
    `  profile: ${quote(name)},\n` +
    `  condition: ${quote(condition)},\n` +
    `  grid: ${GRID},\n` +
    `  data: '${cmyk.toString('base64')}',\n` +
    `} as const;\n`,
);
const black = [...cmyk.subarray(0, 4)].map((v) => Math.round((v / 255) * 100));
console.log(`${out}: ${name}, black C${black[0]} M${black[1]} Y${black[2]} K${black[3]} (${black.reduce((a, b) => a + b)} %)`);
